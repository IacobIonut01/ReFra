package com.dot.gallery.core.ocr.decode

data class OcrSourceRect(
    val left: Int,
    val top: Int,
    val right: Int,
    val bottom: Int,
) {
    init {
        require(left >= 0 && top >= 0 && right > left && bottom > top)
    }

    val width: Int get() = right - left
    val height: Int get() = bottom - top
}
